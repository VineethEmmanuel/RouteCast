import React from "react";
import { cn } from "@/lib/utils";

export const Card: React.FC<React.HTMLAttributes<HTMLDivElement>> = ({
  className,
  children,
  ...props
}) => {
  return (
    <div
      className={cn(
        "rounded-lg border border-[#E7EBEF] bg-white shadow-subtle transition-all duration-150",
        className
      )}
      {...props}
    >
      {children}
    </div>
  );
};

